use std::path::Path;

use mlua::{Function, Lua};

const CTX_TEXT: u32 = 1;
const CTX_EVAL: u32 = 2;
const CTX_COMMENT: u32 = 4;
const CTX_PRINT: u32 = 8;
const CTX_MULTILINE: u32 = 32;

/// Configuration/options.
#[derive(Debug, Clone)]
pub struct EluaConf {
    /// If enabled, comments in ELUA will not propagate to Lua. Default: true.
    pub strip_comments: bool,
    /// If enabled, inserts a call to `send_headers()` before the first print
    /// statement. Default: false.
    pub auto_begin_response_call: bool,
}

impl Default for EluaConf {
    fn default() -> Self {
        Self { strip_comments: true, auto_begin_response_call: false }
    }
}

/// Parser context: the pending buffer and the generated Lua script.
#[derive(Debug, Default)]
pub struct EluaContext {
    buf: String,
    out: String,
    pub conf: EluaConf,
}

impl EluaContext {
    pub fn new() -> Self {
        Self::default()
    }

    /// The Lua source generated by the last parse.
    pub fn output(&self) -> &str {
        &self.out
    }

    /// Reset configuration with default values.
    pub fn reset_conf(&mut self) {
        self.conf = EluaConf::default();
    }

    fn push_buf(&mut self, context: u32, output_started: &mut bool) {
        if self.buf.is_empty() {
            return;
        }
        if self.conf.auto_begin_response_call
            && !*output_started
            && ((context & CTX_PRINT) != 0 || (context & CTX_EVAL) == 0)
        {
            self.out.push_str("send_headers()\n");
            *output_started = true;
        }
        if context & CTX_EVAL != 0 {
            if context & CTX_COMMENT != 0 {
                if !self.conf.strip_comments {
                    if context & CTX_MULTILINE != 0 {
                        self.out.push_str("--[[");
                        self.out.push_str(&self.buf);
                        self.out.push_str("]] ");
                    } else {
                        self.out.push_str("--");
                        self.out.push_str(&self.buf);
                        self.out.push(' ');
                    }
                }
            } else if context & CTX_PRINT != 0 {
                self.out.push_str("print(");
                self.out.push_str(&self.buf);
                self.out.push_str(") ");
            } else {
                self.out.push_str(&self.buf);
                self.out.push(' ');
            }
        } else {
            self.out.push_str("print(\"");
            self.out.push_str(&self.buf);
            self.out.push_str("\") ");
        }
        self.buf.clear();
    }
}

/// Parses a template into Lua source, stored in `ctx`.
pub fn elua_parse(source: &str, ctx: &mut EluaContext) {
    let mut prev_c: Option<char> = None;
    let mut prev_prev_c: Option<char> = None;
    let mut context = CTX_TEXT;
    let mut output_started = false;

    ctx.buf.clear();
    ctx.out.clear();

    for c in source.chars() {
        if context & CTX_TEXT != 0 {
            if prev_c == Some('<') && c == '%' {
                ctx.buf.pop(); // remove '<'
                ctx.push_buf(context, &mut output_started);
                context = CTX_EVAL;
            } else {
                if matches!(c, '"' | '\\' | '\n' | '\r') {
                    ctx.buf.push('\\');
                }
                ctx.buf.push(c);
            }
        } else if context & CTX_EVAL != 0 {
            if prev_c == Some('%') && c == '>' {
                ctx.buf.pop(); // remove '%'
                ctx.push_buf(context, &mut output_started);
                context = CTX_TEXT;
            } else if prev_prev_c == Some('<') && prev_c == Some('%') {
                // the first char after "<%"
                match c {
                    '#' => context |= CTX_COMMENT,
                    '=' => context |= CTX_PRINT,
                    _ => ctx.buf.push(c),
                }
            } else {
                ctx.buf.push(c);
            }
        }
        if c == '\n' {
            context |= CTX_MULTILINE;
        }
        prev_prev_c = prev_c;
        prev_c = Some(c);
    }
    if !ctx.buf.is_empty() {
        ctx.push_buf(context, &mut output_started);
    }
}

/// Parses and loads a template from memory as a Lua function.
pub fn elua_loadbuffer(lua: &Lua, buffer: &str, filename: &str, ctx: &mut EluaContext) -> mlua::Result<Function> {
    elua_parse(buffer, ctx);
    lua.load(ctx.out.as_str()).set_name(filename).into_function()
}

/// Loads an ELUA file. Convenience function.
pub fn elua_loadfile(lua: &Lua, path: &Path, ctx: &mut EluaContext) -> mlua::Result<Function> {
    let source = std::fs::read_to_string(path).map_err(|error| {
        mlua::Error::RuntimeError(format!("Failed to open {} for reading: {}", path.display(), error))
    })?;
    elua_loadbuffer(lua, &source, &format!("@{}", path.display()), ctx)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn render(template: &str) -> String {
        let lua = Lua::new();
        let out = std::rc::Rc::new(std::cell::RefCell::new(String::new()));
        let sink = out.clone();
        let print = lua
            .create_function(move |_, value: mlua::Value| {
                if let Some(text) = value.as_string() {
                    sink.borrow_mut().push_str(&text.to_string_lossy());
                } else if let Some(n) = value.as_i64() {
                    sink.borrow_mut().push_str(&n.to_string());
                }
                Ok(())
            })
            .unwrap();
        lua.globals().set("print", print).unwrap();
        let mut ctx = EluaContext::new();
        elua_loadbuffer(&lua, template, "test", &mut ctx).unwrap().call::<()>(()).unwrap();
        let result = out.borrow().clone();
        result
    }

    #[test]
    fn renders_text_and_expressions() {
        assert_eq!(render("a<%= 1 + 2 %>b"), "a3b");
        assert_eq!(render("<% for i=1,3 do %>x<% end %>"), "xxx");
        assert_eq!(render("\"quoted\"\nline"), "\"quoted\"\nline");
        assert_eq!(render("a<%# comment %>b"), "ab");
    }
}
